"""Unit tests for signal collectors that don't go through the full engine.
AAF integrity + multi-owner detection get direct coverage here since they're
the newest, most safety-critical signals (they drive an --apply-able ini
patch and point at a real load-order collision)."""
from helpers import make_mod_folder

from mod_manager.diagnostics import signals


def test_collect_aaf_integrity_detects_use_signatures_true(patch_config):
    make_mod_folder(
        patch_config.mods,
        "Advanced Animation Framework",
        {"xmlutility.ini": b"[Settings]\nUseSignatures=true\n"},
    )

    sig = signals.collect_aaf_integrity(patch_config.mods)
    assert sig.use_signatures_enabled is True


