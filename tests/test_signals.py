def test_find_aaf_multi_owner_files_detects_real_collision(patch_config):
    # Reproduces the actual confirmed scenario: two mods both ship
    # AAF/Atomic Lust_mfgSetData.xml; Overwrite Mod is listed with HIGHER MO2
    # priority (bottom of modlist.txt) so it wins the collision.
    make_mod_folder(
        patch_config.mods,
        "Atomic Lust",
        {"AAF/Atomic Lust_mfgSetData.xml": b"<data>real content</data>"},
    )
    make_mod_folder(
        patch_config.mods,
        "Overwrite Mod",
        {"AAF/Atomic Lust_mfgSetData.xml": b""},
    )
    patch_config.modlist.parent.mkdir(parents=True, exist_ok=True)
    patch_config.modlist.write_text(
        "# This file was automatically generated by Mod Organizer.\n"
        "+Overwrite Mod\n"
        "+Atomic Lust\n",
        encoding="utf-8",
    )

    collisions = signals.find_aaf_multi_owner_files(patch_config.mods, patch_config.modlist)
    assert len(collisions) == 1
    collision = collisions[0]
    assert collision.relative_path == "AAF/Atomic Lust_mfgSetData.xml"
    assert sorted(collision.owning_mods) == ["Atomic Lust", "Overwrite Mod"]
    assert collision.current_winner == "Overwrite Mod"


def test_find_aaf_multi_owner_files_ignores_single_owner_files(patch_config):
    make_mod_folder(
        patch_config.mods,
        "Atomic Lust",
        {"AAF/Atomic Lust_positionData.xml": b"<data/>"},
    )

    collisions = signals.find_aaf_multi_owner_files(patch_config.mods, patch_config.modlist)
    assert collisions == []
